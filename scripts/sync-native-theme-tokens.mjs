import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const themes = ["gaboma", "soleil", "foret", "corail", "lagon", "electrique", "sable"]
const properties = {
  background: "--background", foreground: "--foreground", card: "--card",
  muted: "--muted", mutedForeground: "--muted-foreground", border: "--border", input: "--input",
  primary: "--primary-fill", primaryOn: "--primary-fill-on", primaryInk: "--primary-500",
  social: "--role-social-fill", socialOn: "--role-social-on", react: "--role-react-ink",
  tabActive: "--esp-tab-active-bg", tabActiveInk: "--esp-tab-active-fg",
  danger: "--role-danger-ink", success: "--role-success-ink",
}

export function readNativeTheme(theme) {
  const source = fs.readFileSync(path.join(root, "packages/ui/src/themes", theme === "gaboma" ? "antsia.css" : `antsia-${theme}.css`), "utf8").replace(/\/\*[\s\S]*?\*\//g, "")
  const light = {}, dark = {}
  for (const [, selector, body] of source.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const values = Object.fromEntries([...body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map(([, key, value]) => [key, value.trim()]))
    Object.assign(selector.includes(".dark") ? dark : light, values)
  }
  return Object.fromEntries(["light", "dark"].map(mode => {
    const variables = mode === "dark" ? { ...light, ...dark } : light
    const resolve = (name, seen = new Set()) => {
      if (seen.has(name) || variables[name] === undefined) throw new Error(`Unresolved native theme token: ${theme}/${mode}/${name}`)
      seen.add(name)
      const value = variables[name].replace(/var\((--[\w-]+)\)/g, (_, next) => resolve(next, new Set(seen)))
      if (!/^#[a-f\d]{6}$/i.test(value)) throw new Error(`Non-color native theme token: ${theme}/${mode}/${name}`)
      return value
    }
    return [mode, { ...Object.fromEntries(Object.entries(properties).map(([key, name]) => [key, resolve(name)])), radiusCard: 16, radiusField: 14, radiusMedia: 12 }]
  }))
}

const projection = Object.fromEntries(themes.map(theme => [theme, readNativeTheme(theme)]))
const output = `/** Generated by scripts/sync-native-theme-tokens.mjs from the seven Web theme sources. */\nimport type { ANTSIA_THEME_IDS } from "./antsia-themes"\n\ntype NativeThemeId = (typeof ANTSIA_THEME_IDS)[number]\nexport type NativeThemeAppearance = "light" | "dark"\nexport type NativeThemeTokens = Readonly<{\n${Object.keys(properties).map(key => `  ${key}: string`).join("\n")}\n  radiusCard: number\n  radiusField: number\n  radiusMedia: number\n}>\n\nconst tokens = ${JSON.stringify(projection, null, 2)} as const satisfies Readonly<Record<NativeThemeId, Readonly<Record<NativeThemeAppearance, NativeThemeTokens>>>>\n\nexport function nativeThemeTokens(theme: NativeThemeId, appearance: NativeThemeAppearance): NativeThemeTokens {\n  return tokens[theme][appearance]\n}\n`
const target = path.join(root, "packages/ui/src/themes/antsia-native.ts")
if (process.argv.includes("--check")) {
  if (fs.readFileSync(target, "utf8") !== output) throw new Error("Native themes differ from Web themes. Run: bun scripts/sync-native-theme-tokens.mjs")
} else fs.writeFileSync(target, output)
